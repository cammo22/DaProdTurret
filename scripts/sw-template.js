export function buildServiceWorker(files, revision) {
  if (!Array.isArray(files) || files.some(file => typeof file !== 'string' || file.startsWith('/') || file.includes('..') || file.includes(':'))) {
    throw new Error('Service worker assets must use safe relative paths');
  }
  return `// Generated by DaProdTurret. Do not add credentials to this file.
const PREFIX = 'daprod-turret:' + encodeURIComponent(self.registration.scope) + ':';
const CACHE = PREFIX + ${JSON.stringify(revision)};
const FILES = ${JSON.stringify(files)};
const absolute = path => new URL(path, self.registration.scope).href;
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES.map(absolute))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith(PREFIX) && key !== CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET' || !event.request.url.startsWith(self.registration.scope)) return;
  if (event.request.mode === 'navigate') {
    event.respondWith(fetch(event.request).catch(async () => {
      const cache = await caches.open(CACHE);
      return (await cache.match(absolute('index.html'))) || Response.error();
    }));
    return;
  }
  // Files are immutable, same-origin static build artifacts, never authenticated responses.
  event.respondWith(caches.open(CACHE).then(async cache => (await cache.match(event.request, { ignoreVary: true })) || fetch(event.request)));
});
`;
}
